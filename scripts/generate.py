#!/usr/bin/env python3
"""SS-026 §5: writes src/storeshot/_generated/{schemas,operations}.py from the platform OpenAPI
contract (located by scripts/inputs.py). Stdlib only and deterministic. `--check` generates twice
and fails when the runs differ or differ from the committed files; `--print-operations` prints the
operations table as JSON (the monorepo parity test compares it with the TypeScript SDK's). Never
edit the generated files by hand.
"""

from __future__ import annotations

import json
import keyword
import re
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inputs import PACKAGE_ROOT, input_path  # noqa: E402

OUT = PACKAGE_ROOT / "src" / "storeshot" / "_generated"
METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")
REF = "#/components/schemas/"
BODY_KINDS = {"application/json": "json", "multipart/form-data": "multipart"}


def ref_name(ref: str) -> str:
    if not ref.startswith(REF):
        raise ValueError(f"unsupported $ref {ref}")
    return ref[len(REF) :]


def schema_refs(schema: dict[str, Any]) -> list[str]:
    """Component names a response schema stands for: a $ref, or an anyOf of $refs."""
    if "$ref" in schema:
        return [ref_name(schema["$ref"])]
    return sorted(name for alt in schema.get("anyOf", []) for name in schema_refs(alt))


def describe_operations(spec: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """One entry per operationId: the TS SDK's describeOperations fields plus schema names."""
    operations: dict[str, dict[str, Any]] = {}
    for path, item in spec["paths"].items():
        for method in METHODS:
            op = item.get(method)
            if not op or "operationId" not in op:
                continue
            oid = op["operationId"]
            if oid in operations:
                raise ValueError(f"duplicate operationId {oid}")
            params = [*item.get("parameters", []), *op.get("parameters", [])]

            def named(where: str, params: list[dict[str, Any]] = params) -> list[str]:
                return [p["name"] for p in params if p["in"] == where]

            content = op.get("requestBody", {}).get("content", {})
            body = "|".join(sorted(BODY_KINDS.get(t, t) for t in content)) if content else "none"
            responses = op.get("responses", {})
            success = sorted(int(s) for s in responses if re.fullmatch(r"2\d\d", s))
            json_answers = [
                responses[str(s)]["content"]["application/json"]["schema"]
                for s in success
                if "application/json" in responses[str(s)].get("content", {})
            ]
            json_body = content.get("application/json", {}).get("schema", {})
            operations[oid] = {
                "method": method.upper(),
                "path": path,
                "tag": (op.get("tags") or [None])[0],
                "idempotency_key": "idempotency-key" in named("header"),
                "wait": "wait" in named("query"),
                "path_params": named("path"),
                "query_params": sorted(named("query")),
                "body": body,
                "success_statuses": success,
                "binary": any(
                    t != "application/json"
                    for s in success
                    for t in responses[str(s)].get("content", {})
                ),
                "request_schema": ref_name(json_body["$ref"]) if "$ref" in json_body else None,
                "response_schemas": sorted({n for s in json_answers for n in schema_refs(s)}),
            }
    return dict(sorted(operations.items()))


# --- schemas.py -------------------------------------------------------------------------------

TYPE_KEYS = {
    "type",
    "properties",
    "required",
    "items",
    "enum",
    "$ref",
    "allOf",
    "anyOf",
    "additionalProperties",
    "format",
}
ANNOTATION_KEYS = {
    "description",
    "default",
    "example",
    "exclusiveMinimum",
    "maxItems",
    "maxLength",
    "maximum",
    "minItems",
    "minLength",
    "minimum",
    "pattern",
}
KNOWN_KEYS = TYPE_KEYS | ANNOTATION_KEYS
SCALARS = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}

SCHEMAS_HEADER = '''\
# Generated by scripts/generate.py from the platform OpenAPI contract {version}. Do not edit:
# run `uv run python scripts/generate.py` after a contract change.
"""Every schema of the Storeshot API contract as a TypedDict or Literal (keys = the API's names)."""

import sys
from typing import Any, Dict, List, Literal, Optional, TypeAlias, Union

if sys.version_info >= (3, 11):
    from typing import NotRequired, TypedDict
else:
    from typing_extensions import NotRequired, TypedDict


'''


class UnsupportedSchema(Exception):
    """A schema construct the generator does not map (it never guesses a type)."""


def pascal(text: str) -> str:
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", text) if w)


def literal(value: Any) -> str:
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, (int, float)):
        return repr(value)
    return json.dumps(value, ensure_ascii=False)


def quote(name: str) -> str:
    return f'"{name}"'


def docstring(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    body = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if body.endswith('"'):
        body += " "
    return [f'{indent}"""{body}"""']


class SchemaWriter:
    def __init__(self, spec: dict[str, Any]) -> None:
        self.components: dict[str, Any] = spec.get("components", {}).get("schemas", {})
        self.blocks: dict[str, str] = {}
        # Object components typed [object, null]: the class is the object, every $ref is Optional.
        self.nullable = {
            name
            for name, s in self.components.items()
            if "properties" in s and isinstance(s.get("type"), list) and "null" in s["type"]
        }

    def ref(self, ref: str) -> str:
        name = ref_name(ref)
        return f"Optional[{quote(name)}]" if name in self.nullable else quote(name)

    def check_keys(self, schema: dict[str, Any], where: str) -> None:
        unknown = sorted(set(schema) - KNOWN_KEYS)
        if unknown:
            raise UnsupportedSchema(f"{where}: unsupported schema keyword(s) {unknown}")

    def new_name(self, hint: str) -> str:
        name = hint
        if name in self.components or name in self.blocks:
            name = f"{hint}Inline"
        if name in self.components or name in self.blocks:
            raise UnsupportedSchema(f"{hint}: no free class name")
        return name

    def type_of(self, schema: Any, hint: str) -> str:
        if not isinstance(schema, dict):
            raise UnsupportedSchema(f"{hint}: schema is not an object")
        self.check_keys(schema, hint)
        if "$ref" in schema:
            return self.ref(schema["$ref"])
        if "allOf" in schema:
            merged = self.merge_all_of(schema, hint)
            if isinstance(merged, str):
                return self.ref(REF + merged)
            return self.object_type(merged, hint)
        if "anyOf" in schema:
            alts = [self.type_of(a, f"{hint}Variant{i}") for i, a in enumerate(schema["anyOf"], 1)]
            return f"Union[{', '.join(alts)}]"
        declared = schema.get("type")
        kinds = declared if isinstance(declared, list) else [declared] if declared else []
        nullable = "null" in kinds
        base = [k for k in kinds if k != "null"]
        if len(base) > 1:
            raise UnsupportedSchema(f"{hint}: several types {base}")
        kind = base[0] if base else None
        if "enum" in schema:
            values = [v for v in schema["enum"] if v is not None]
            nullable = nullable or None in schema["enum"]
            expr = f"Literal[{', '.join(literal(v) for v in values)}]"
        elif kind == "object" or "properties" in schema:
            expr = self.object_type(schema, hint)
        elif kind == "array":
            if "items" not in schema:
                raise UnsupportedSchema(f"{hint}: array without items")
            expr = f"List[{self.type_of(schema['items'], hint + 'Item')}]"
        elif kind == "string" and schema.get("format") == "binary":
            expr = "bytes"
        elif kind in SCALARS:
            expr = SCALARS[kind]
        elif kind is None:
            expr = "Any"
        else:
            raise UnsupportedSchema(f"{hint}: unsupported type {kind}")
        return f"Optional[{expr}]" if nullable else expr

    def resolve(self, schema: dict[str, Any], where: str) -> dict[str, Any]:
        """An object schema with every property, following $ref and allOf (for merging)."""
        if "$ref" in schema:
            return self.resolve(self.components[ref_name(schema["$ref"])], where)
        if "allOf" in schema:
            merged = self.merge_all_of(schema, where)
            return (
                self.resolve({"$ref": REF + merged}, where) if isinstance(merged, str) else merged
            )
        if "properties" not in schema:
            raise UnsupportedSchema(f"{where}: allOf over a schema without properties")
        return schema

    def merge_all_of(self, schema: dict[str, Any], where: str) -> str | dict[str, Any]:
        """allOf = one $ref plus annotations (→ the ref's name), or one $ref plus object
        extensions (→ one merged object; an extension's property replaces the base's)."""
        parts = schema["allOf"]
        refs = [p for p in parts if "$ref" in p]
        others = [p for p in parts if "$ref" not in p]
        if len(refs) != 1:
            raise UnsupportedSchema(f"{where}: allOf needs exactly one $ref")
        for part in others:
            self.check_keys(part, where)
        if all(not (set(p) - ANNOTATION_KEYS) for p in others):
            return ref_name(refs[0]["$ref"])
        base = self.resolve(refs[0], where)
        properties = dict(base["properties"])
        required = set(base.get("required", []))
        for part in others:
            if (
                set(part)
                - ANNOTATION_KEYS
                - {"type", "properties", "required", "additionalProperties"}
            ):
                raise UnsupportedSchema(f"{where}: unsupported allOf extension")
            properties.update(part.get("properties", {}))
            required |= set(part.get("required", []))
        description = schema.get("description") or base.get("description")
        merged: dict[str, Any] = {"type": "object", "properties": properties}
        if required:
            merged["required"] = sorted(required)
        if description:
            merged["description"] = description
        return merged

    def object_type(self, schema: dict[str, Any], hint: str) -> str:
        if not schema.get("properties"):
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"Dict[str, {self.type_of(extra, hint + 'Value')}]"
            return "Dict[str, Any]"
        name = self.new_name(hint)
        self.emit_class(name, schema)
        return quote(name)

    def emit_class(self, name: str, schema: dict[str, Any], total: bool = True) -> None:
        self.blocks[name] = ""  # reserve the name before nested classes are named
        required = set(schema.get("required", []))
        fields: list[tuple[str, str, str | None]] = []
        for key in sorted(schema["properties"]):
            sub = schema["properties"][key]
            expr = self.type_of(sub, name + pascal(key))
            if total and key not in required:
                expr = f"NotRequired[{expr}]"
            fields.append((key, expr, sub.get("description") if isinstance(sub, dict) else None))
        suffix = "" if total else ", total=False"
        if all(k.isidentifier() and not keyword.iskeyword(k) for k, _, _ in fields):
            lines = [f"class {name}(TypedDict{suffix}):"]
            lines += docstring(schema.get("description"), "    ")
            for key, expr, doc in fields:
                lines.append(f"    {key}: {expr}")
                lines.extend(docstring(doc, "    "))
        else:
            lines = [
                f"# {line}".rstrip() for line in (schema.get("description") or "").splitlines()
            ]
            lines += [f"{name} = TypedDict(", f"    {quote(name)},", "    {"]
            lines += [f"        {json.dumps(key)}: {expr}," for key, expr, _ in fields]
            lines += ["    },"]
            lines += [] if total else ["    total=False,"]
            lines += [")"]
        self.blocks[name] = "\n".join(lines) + "\n"

    def component(self, name: str, schema: dict[str, Any]) -> None:
        self.check_keys(schema, name)
        if "allOf" in schema:
            merged = self.merge_all_of(schema, name)
            if not isinstance(merged, str):
                self.emit_class(name, merged)
                return
        is_object = "properties" in schema and not (
            {"anyOf", "allOf", "$ref", "enum"} & set(schema)
        )
        if is_object:
            self.emit_class(name, schema)
            return
        self.blocks[name] = ""
        expr = self.type_of(schema, name)
        lines = [f"# {line}".rstrip() for line in (schema.get("description") or "").splitlines()]
        self.blocks[name] = "\n".join([*lines, f"{name}: TypeAlias = {expr}"]) + "\n"

    def query(self, oid: str, params: list[dict[str, Any]]) -> None:
        name = self.new_name(f"{oid[:1].upper()}{oid[1:]}Query")
        properties: dict[str, Any] = {}
        for p in params:
            prop = dict(p["schema"])
            description = p.get("description") or prop.get("description")
            prop.pop("description", None)
            if description:
                prop["description"] = description
            properties[p["name"]] = prop
        self.emit_class(name, {"properties": properties}, total=False)


def schemas_source(spec: dict[str, Any]) -> str:
    writer = SchemaWriter(spec)
    for name in sorted(writer.components):
        writer.component(name, writer.components[name])
    for item in spec.get("paths", {}).values():
        for method in METHODS:
            op = item.get(method)
            if not op or "operationId" not in op:
                continue
            params = [
                p
                for p in [*item.get("parameters", []), *op.get("parameters", [])]
                if p["in"] == "query"
            ]
            if params:
                writer.query(op["operationId"], params)
    events = sorted(
        ref_name(hook["post"]["requestBody"]["content"]["application/json"]["schema"]["$ref"])
        for hook in spec.get("webhooks", {}).values()
    )
    if events:
        writer.blocks["WebhookEvent"] = (
            '# Every webhook event of the contract; narrow on event["type"].\n'
            f"WebhookEvent: TypeAlias = Union[{', '.join(quote(e) for e in events)}]\n"
        )
    names = sorted(writer.blocks)
    exports = "__all__ = [\n" + "".join(f"    {quote(n)},\n" for n in names) + "]\n"
    body = "\n\n".join(writer.blocks[n] for n in names)
    return SCHEMAS_HEADER.format(version=spec["info"]["version"]) + body + "\n\n" + exports


# --- operations.py ----------------------------------------------------------------------------

OPERATIONS_HEADER = '''\
# Generated by scripts/generate.py from the platform OpenAPI contract {version}. Do not edit:
# run `uv run python scripts/generate.py` after a contract change.
"""The contract version, error codes, webhook event types and every operation's traits."""

from typing import Final, Literal, Mapping, TypeAlias

from .._core.operation import Operation
'''

FIELDS = (
    "method",
    "path",
    "tag",
    "idempotency_key",
    "wait",
    "path_params",
    "query_params",
    "body",
    "success_statuses",
    "binary",
    "request_schema",
    "response_schemas",
)


def tuple_src(values: list[Any]) -> str:
    inner = ", ".join(literal(v) for v in values)
    return f"({inner},)" if len(values) == 1 else f"({inner})"


def operations_source(spec: dict[str, Any]) -> str:
    ops = describe_operations(spec)
    codes = spec["components"]["schemas"]["ErrorCode"]["enum"]
    events = sorted(spec.get("webhooks", {}))
    lines = [
        OPERATIONS_HEADER.format(version=spec["info"]["version"]),
        f"CONTRACT_VERSION: Final = {json.dumps(spec['info']['version'])}",
        "",
        "#: Every ErrorCode of the contract (ErrorEnvelope.error.code), contract order.",
        f"ERROR_CODES: Final = {tuple_src(codes)}",
        "",
        "#: Every webhook event type of the contract.",
        f"WEBHOOK_EVENT_TYPES: Final = {tuple_src(events)}",
        "",
        f"WebhookEventType: TypeAlias = Literal[{', '.join(literal(e) for e in events)}]",
        f"OperationId: TypeAlias = Literal[{', '.join(literal(o) for o in ops)}]",
        "",
        "OPERATIONS: Final[Mapping[str, Operation]] = {",
    ]
    for oid, op in ops.items():
        lines.append(f"    {json.dumps(oid)}: Operation(")
        for field in FIELDS:
            value = op[field]
            if isinstance(value, list):
                text = tuple_src(value)
            elif value is None:
                text = "None"
            else:
                text = literal(value)
            lines.append(f"        {field}={text},")
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate(spec: dict[str, Any]) -> dict[str, str]:
    return {"schemas.py": schemas_source(spec), "operations.py": operations_source(spec)}


def load() -> dict[str, Any]:
    spec: dict[str, Any] = json.loads(input_path("contract").read_text("utf-8"))
    return spec


def main(argv: list[str]) -> int:
    spec = load()
    if "--print-operations" in argv:
        print(json.dumps(describe_operations(spec), indent=2))
        return 0
    first = generate(spec)
    if "--check" in argv:
        if generate(load()) != first:
            print(
                "src/storeshot/_generated is non-deterministic: two runs differ.", file=sys.stderr
            )
            return 1
        for name, text in first.items():
            target = OUT / name
            current = target.read_text("utf-8") if target.is_file() else ""
            if current != text:
                print(
                    f"src/storeshot/_generated/{name} is stale: "
                    "run `uv run python scripts/generate.py`.",
                    file=sys.stderr,
                )
                return 1
        print(f"src/storeshot/_generated matches the contract ({spec['info']['version']})")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in first.items():
        (OUT / name).write_text(text, "utf-8", newline="\n")
    version = spec["info"]["version"]
    print(f"wrote src/storeshot/_generated/{{schemas,operations}}.py (contract {version})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
